function translate(key, lang = currentLanguage) {
    const translations = TRANSLATIONS[lang] || TRANSLATIONS.fr;
    return translations[key] || key;
}

function applyLanguage(lang) {
    currentLanguage = lang;
    localStorage.setItem('sine_language', lang);
    
    // Appliquer à tous les éléments avec data-translate
    document.querySelectorAll('[data-translate]').forEach(el => {
        const key = el.getAttribute('data-translate');
        const translation = translate(key, lang);
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA' || el.tagName === 'SELECT') {
            el.placeholder = translation;
        } else {
            el.textContent = translation;
        }
    });
    
    // Mettre à jour les sélecteurs de langue
    document.querySelectorAll('.lang-select, #langSelect, #headerLangSelect').forEach(el => {
        if (el.value !== lang) el.value = lang;
    });

    // 🔴 CORRECTIF — appliqué directement ici (donc sur TOUTES les pages du
    // site, pas seulement celles qui appellent explicitement
    // applyDirection ci-dessous) : sans ceci, la page restait TOUJOURS de
    // gauche à droite même en arabe — texte arabe affiché dans une mise en
    // page pensée pour un sens de lecture gauche→droite, illisible et
    // visuellement cassé. applyDirection() était en plus appelée par 6
    // pages (login/register*) alors qu'elle n'existait nulle part dans ce
    // fichier — plantage JavaScript garanti à chaque changement de langue
    // sur ces pages précises avant ce correctif.
    applyDirection(lang);
    
    // Émettre un événement pour les autres pages
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { language: lang } }));
}

// Bascule la mise en page en RTL (arabe) ou LTR (toutes les autres langues
// supportées) — n'existait pas du tout avant ce correctif.
function applyDirection(lang) {
    const isRtl = lang === 'ar';
    document.documentElement.setAttribute('dir', isRtl ? 'rtl' : 'ltr');
    document.documentElement.setAttribute('lang', lang);
    document.body?.classList.toggle('rtl-active', isRtl);
}

